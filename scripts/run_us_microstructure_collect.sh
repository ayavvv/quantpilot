#!/bin/bash
# QuantPilot US microstructure live collector.

set -euo pipefail

export PATH="/opt/homebrew/bin:/opt/homebrew/sbin:/usr/local/bin:/usr/bin:/bin:/usr/sbin:/sbin"

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_DIR"

EXTERNAL_DATA_DIR="${DATA_DIR-}"
EXTERNAL_FUTU_HOST="${FUTU_HOST-}"
EXTERNAL_FUTU_PORT="${FUTU_PORT-}"
EXTERNAL_FUTU_RSA_KEY="${FUTU_RSA_KEY-}"
EXTERNAL_US_MICROSTRUCTURE_DIR="${US_MICROSTRUCTURE_DIR-}"
EXTERNAL_US_MICROSTRUCTURE_SYMBOLS="${US_MICROSTRUCTURE_SYMBOLS-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_FILE="${US_MICROSTRUCTURE_UNIVERSE_FILE-}"
EXTERNAL_US_MICROSTRUCTURE_BUILD_UNIVERSE="${US_MICROSTRUCTURE_BUILD_UNIVERSE-}"
EXTERNAL_US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE="${US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE="${US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE="${US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE="${US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE="${US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE-}"
EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE="${US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE-}"
EXTERNAL_US_MICROSTRUCTURE_NAS_HOST="${US_MICROSTRUCTURE_NAS_HOST-}"
EXTERNAL_US_MICROSTRUCTURE_NAS_DIR="${US_MICROSTRUCTURE_NAS_DIR-}"
EXTERNAL_US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS="${US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS-}"
EXTERNAL_US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS="${US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS-}"
EXTERNAL_US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS="${US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS-}"
EXTERNAL_US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS="${US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS-}"
EXTERNAL_US_MICROSTRUCTURE_BATCH_SECONDS="${US_MICROSTRUCTURE_BATCH_SECONDS-}"
EXTERNAL_US_MICROSTRUCTURE_BOOK_LEVELS="${US_MICROSTRUCTURE_BOOK_LEVELS-}"
EXTERNAL_US_MICROSTRUCTURE_NO_NAS_SYNC="${US_MICROSTRUCTURE_NO_NAS_SYNC-}"

if [ -f "$PROJECT_DIR/.env" ]; then
    set -a
    source "$PROJECT_DIR/.env"
    set +a
fi

[ -n "$EXTERNAL_DATA_DIR" ] && DATA_DIR="$EXTERNAL_DATA_DIR"
[ -n "$EXTERNAL_FUTU_HOST" ] && FUTU_HOST="$EXTERNAL_FUTU_HOST"
[ -n "$EXTERNAL_FUTU_PORT" ] && FUTU_PORT="$EXTERNAL_FUTU_PORT"
[ -n "$EXTERNAL_FUTU_RSA_KEY" ] && FUTU_RSA_KEY="$EXTERNAL_FUTU_RSA_KEY"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_DIR" ] && US_MICROSTRUCTURE_DIR="$EXTERNAL_US_MICROSTRUCTURE_DIR"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_SYMBOLS" ] && US_MICROSTRUCTURE_SYMBOLS="$EXTERNAL_US_MICROSTRUCTURE_SYMBOLS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_FILE" ] && US_MICROSTRUCTURE_UNIVERSE_FILE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_FILE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_BUILD_UNIVERSE" ] && US_MICROSTRUCTURE_BUILD_UNIVERSE="$EXTERNAL_US_MICROSTRUCTURE_BUILD_UNIVERSE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE" ] && US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE="$EXTERNAL_US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE" ] && US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE" ] && US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE" ] && US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE" ] && US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE" ] && US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE="$EXTERNAL_US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_NAS_HOST" ] && US_MICROSTRUCTURE_NAS_HOST="$EXTERNAL_US_MICROSTRUCTURE_NAS_HOST"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_NAS_DIR" ] && US_MICROSTRUCTURE_NAS_DIR="$EXTERNAL_US_MICROSTRUCTURE_NAS_DIR"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS" ] && US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS="$EXTERNAL_US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS" ] && US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS="$EXTERNAL_US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS" ] && US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS="$EXTERNAL_US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS" ] && US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS="$EXTERNAL_US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_BATCH_SECONDS" ] && US_MICROSTRUCTURE_BATCH_SECONDS="$EXTERNAL_US_MICROSTRUCTURE_BATCH_SECONDS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_BOOK_LEVELS" ] && US_MICROSTRUCTURE_BOOK_LEVELS="$EXTERNAL_US_MICROSTRUCTURE_BOOK_LEVELS"
[ -n "$EXTERNAL_US_MICROSTRUCTURE_NO_NAS_SYNC" ] && US_MICROSTRUCTURE_NO_NAS_SYNC="$EXTERNAL_US_MICROSTRUCTURE_NO_NAS_SYNC"

DATA_DIR="${DATA_DIR:-$HOME/quantpilot_data}"
PYTHON_BIN="${PYTHON_BIN:-$PROJECT_DIR/.venv/bin/python}"
PYTHONPATH="${PROJECT_DIR}${PYTHONPATH:+:$PYTHONPATH}"
FUTU_HOST="${FUTU_HOST:-127.0.0.1}"
FUTU_PORT="${FUTU_PORT:-11111}"
FUTU_RSA_KEY="${FUTU_RSA_KEY:-$PROJECT_DIR/keys/futu_rsa_1024.pem}"
US_MICROSTRUCTURE_DIR="${US_MICROSTRUCTURE_DIR:-$DATA_DIR/us_microstructure}"
US_MICROSTRUCTURE_SYMBOLS="${US_MICROSTRUCTURE_SYMBOLS:-}"
US_MICROSTRUCTURE_UNIVERSE_FILE="${US_MICROSTRUCTURE_UNIVERSE_FILE:-$PROJECT_DIR/config/us_microstructure_core_symbols.txt}"
US_MICROSTRUCTURE_BUILD_UNIVERSE="${US_MICROSTRUCTURE_BUILD_UNIVERSE:-true}"
US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE="${US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE:-$US_MICROSTRUCTURE_DIR/universe/us_microstructure_candidates_latest.txt}"
US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE="${US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE:-300}"
US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE="${US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE:-500}"
US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE="${US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE:-300}"
US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE="${US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE:-false}"
US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE="${US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE:-false}"
US_MICROSTRUCTURE_NAS_HOST="${US_MICROSTRUCTURE_NAS_HOST:-nas}"
US_MICROSTRUCTURE_NAS_DIR="${US_MICROSTRUCTURE_NAS_DIR:-/volume1/docker/quantpilot/us_microstructure}"
US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS="${US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS:-30000}"
US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS="${US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS:-1}"
US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS="${US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS:-1}"
US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS="${US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS:-5}"
US_MICROSTRUCTURE_BATCH_SECONDS="${US_MICROSTRUCTURE_BATCH_SECONDS:-60}"
US_MICROSTRUCTURE_BOOK_LEVELS="${US_MICROSTRUCTURE_BOOK_LEVELS:-10}"
US_MICROSTRUCTURE_NO_NAS_SYNC="${US_MICROSTRUCTURE_NO_NAS_SYNC:-false}"
LOCK_DIR="${LOCK_DIR:-$PROJECT_DIR/logs/us_microstructure_collect.lock}"

log() {
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] $*"
}

mkdir -p "$PROJECT_DIR/logs" "$US_MICROSTRUCTURE_DIR"
if ! mkdir "$LOCK_DIR" 2>/dev/null; then
    log "run_us_microstructure_collect: skip (lock exists: $LOCK_DIR)"
    exit 0
fi
trap 'rmdir "$LOCK_DIR"' EXIT

if [ "$US_MICROSTRUCTURE_BUILD_UNIVERSE" = "true" ] && [ -z "$US_MICROSTRUCTURE_SYMBOLS" ]; then
    universe_args=(
        --base-dir "$US_MICROSTRUCTURE_DIR"
        --target-size "$US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE"
        --core-symbols-file "$PROJECT_DIR/config/us_microstructure_core_symbols.txt"
        --history-pool-size "$US_MICROSTRUCTURE_UNIVERSE_HISTORY_POOL_SIZE"
        --minute-pool-size "$US_MICROSTRUCTURE_UNIVERSE_MINUTE_POOL_SIZE"
        --host "$FUTU_HOST"
        --port "$FUTU_PORT"
        --rsa-key "$FUTU_RSA_KEY"
        --nas-host "$US_MICROSTRUCTURE_NAS_HOST"
        --nas-dir "$US_MICROSTRUCTURE_NAS_DIR"
    )
    if [ "$US_MICROSTRUCTURE_UNIVERSE_SKIP_DAILY_KLINE" = "true" ]; then
        universe_args+=(--skip-daily-kline)
    fi
    if [ "$US_MICROSTRUCTURE_UNIVERSE_SKIP_MINUTE_KLINE" = "true" ]; then
        universe_args+=(--skip-minute-kline)
    fi
    if [ "$US_MICROSTRUCTURE_NO_NAS_SYNC" = "true" ]; then
        universe_args+=(--no-nas-sync)
    fi

    log "run_us_microstructure_collect: build dynamic universe target=${US_MICROSTRUCTURE_UNIVERSE_TARGET_SIZE}"
    if PYTHONPATH="$PYTHONPATH" DATA_DIR="$DATA_DIR" "$PYTHON_BIN" -m scripts.build_us_microstructure_universe "${universe_args[@]}"; then
        if [ -s "$US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE" ]; then
            US_MICROSTRUCTURE_UNIVERSE_FILE="$US_MICROSTRUCTURE_DYNAMIC_UNIVERSE_FILE"
            log "run_us_microstructure_collect: using dynamic universe $US_MICROSTRUCTURE_UNIVERSE_FILE"
        else
            log "run_us_microstructure_collect: dynamic universe file empty, fallback to $US_MICROSTRUCTURE_UNIVERSE_FILE"
        fi
    else
        log "run_us_microstructure_collect: dynamic universe build failed, fallback to $US_MICROSTRUCTURE_UNIVERSE_FILE"
    fi
fi

args=(
    --duration-seconds "$US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS"
    --poll-interval-seconds "$US_MICROSTRUCTURE_POLL_INTERVAL_SECONDS"
    --book-interval-seconds "$US_MICROSTRUCTURE_BOOK_INTERVAL_SECONDS"
    --quote-interval-seconds "$US_MICROSTRUCTURE_QUOTE_INTERVAL_SECONDS"
    --batch-seconds "$US_MICROSTRUCTURE_BATCH_SECONDS"
    --book-levels "$US_MICROSTRUCTURE_BOOK_LEVELS"
    --host "$FUTU_HOST"
    --port "$FUTU_PORT"
    --rsa-key "$FUTU_RSA_KEY"
    --local-dir "$US_MICROSTRUCTURE_DIR"
    --nas-host "$US_MICROSTRUCTURE_NAS_HOST"
    --nas-dir "$US_MICROSTRUCTURE_NAS_DIR"
)

if [ -n "$US_MICROSTRUCTURE_SYMBOLS" ]; then
    args+=(--symbols "$US_MICROSTRUCTURE_SYMBOLS")
elif [ -f "$US_MICROSTRUCTURE_UNIVERSE_FILE" ]; then
    args+=(--universe-file "$US_MICROSTRUCTURE_UNIVERSE_FILE")
fi

if [ "$US_MICROSTRUCTURE_NO_NAS_SYNC" = "true" ]; then
    args+=(--no-nas-sync)
fi

log "run_us_microstructure_collect: start duration=${US_MICROSTRUCTURE_COLLECT_DURATION_SECONDS}s"
PYTHONPATH="$PYTHONPATH" DATA_DIR="$DATA_DIR" "$PYTHON_BIN" -m scripts.collect_us_microstructure "${args[@]}"
log "run_us_microstructure_collect: done"
